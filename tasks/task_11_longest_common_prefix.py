"""
Задание 11: Общий префикс слов
Описание:
Введите несколько слов через пробел. Найдите самую длинную общую
начальную часть всех слов. Если общей части нет, выведите сообщение
"Нет общего префикса".

Пример:
Ввод: программа программист программирование
Вывод: программ
"""


def find_longest_common_prefix(text: str) -> str:
    """
    Находит наибольший общий префикс среди слов, разделённых пробелами.
    Использует подход последовательного укорачивания префикса первого слова.
    """
    words = text.split()
    if not words:
        return "Нет общего префикса"
        
    prefix = words[0]
    
    for word in words[1:]:
        # Пока текущее слово не начинается с префикса, укорачиваем префикс на 1 символ
        while not word.startswith(prefix):
            prefix = prefix[:-1]
            if not prefix:
                return "Нет общего префикса"
                
    return prefix if prefix else "Нет общего префикса"


def main() -> None:
    print("=== Задание 11: Общий префикс слов ===")
    user_input = input("Введите несколько слов через пробел: ")
    prefix = find_longest_common_prefix(user_input)
    print(f"Вывод: {prefix}")


if __name__ == "__main__":
    main()
