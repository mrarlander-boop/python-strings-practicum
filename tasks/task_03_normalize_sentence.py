"""
Задание 3: Нормализация предложения
Описание:
Введите предложение с ошибками в регистре и лишними пробелами.
Сделайте первую букву прописной, остальные — строчными, удалите лишние
пробелы и добавьте точку в конце, если её нет.

Пример:
Ввод: пРИВЕТ, МИР
Вывод: Привет, мир.
"""


def normalize_sentence(text: str) -> str:
    """
    Нормализует предложение:
    1. Удаляет повторяющиеся и краевые пробелы через split() и join()
    2. Приводит к нижнему регистру и делает первую букву заглавной
    3. Добавляет точку в конец, если её там нет.
    """
    # 1. Удаляем лишние пробелы между словами
    words = text.split()
    if not words:
        return ""
        
    cleaned_spaces = " ".join(words)
    
    # 2. Приводим буквы к правильному регистру
    # lower() делает все буквы строчными, capitalize() делает первую букву заглавной
    normalized = cleaned_spaces.lower().capitalize()
    
    # 3. Проверяем наличие точки в конце строки
    if not normalized.endswith("."):
        normalized += "."
        
    return normalized


def main() -> None:
    print("=== Задание 3: Нормализация предложения ===")
    user_input = input("Введите предложение: ")
    normalized = normalize_sentence(user_input)
    print(f"Вывод: {normalized}")


if __name__ == "__main__":
    main()
